/* 02 · Thực trạng — 3 ý
 * ý 1: dữ liệu nằm rải rác ở nhiều hệ thống (lõi vỡ thành 13 hệ thống)
 * ý 2: lãnh đạo hỏi "hôm nay có gì cần chú ý?" → nhân viên phải tự mở, lọc, xuất Excel, tổng hợp…
 * ý 3: bài toán tiếp theo: khai thác nhanh hơn, đúng ngữ cảnh, ít thao tác thủ công */
E.def(1, (S) => {
  const { t, $$ } = S, b = S.beat;

  t('.head', [[-0.02, { o: 0, y: 30 }], [0.06, { o: 1, y: 0 }], [b(3, 0), { o: 1, y: 0 }], [b(3, 0.3), { o: 0, y: '-4vh' }]]);

  const rows = [[-2, [-37.8, -29.4, -21, -12.6]], [12, [-42, -33.6, -25.2, -16.8, -8.4]], [26, [-37.8, -29.4, -21, -12.6]]];
  const pos = [];
  rows.forEach(([y, xs]) => xs.forEach((x) => pos.push([x, y])));
  $$('.tile').forEach((el, k) => {
    const [X, Y] = pos[k];
    const rot = ((k * 47) % 70) - 35;
    t([el], [
      [0.0, { x: 0, y: '4vh', s: 0.2, o: 0, r: rot }],
      [b(1, 0.05 + k * 0.03), { o: 1 }],
      [b(1, 0.3 + k * 0.04), { x: X + 'vw', y: Y + 'vh', s: 1, r: 0 }, 'b'],
      [b(3, 0.05 + k * 0.01), { x: X + 'vw', y: Y + 'vh', s: 1, o: 1 }],
      [b(3, 0.45 + k * 0.01), { x: 0, y: '4vh', s: 0.3, o: 0 }, 'i'],
    ]);
  });

  // ý 2
  // ý 2 — Lãnh đạo hỏi → nhân viên phải tự làm cả chuỗi thủ công
  t('.boss', [[b(2, 0), { o: 0, y: -20 }], [b(2, 0.15), { o: 1, y: 0 }, 'b'], [b(3, 0), { o: 1 }], [b(3, 0.2), { o: 0 }]]);
  t('.pipe-l', [[b(2, 0.12), { o: 0, x: -16 }], [b(2, 0.24), { o: 1, x: 0 }], [b(3, 0), { o: 1 }], [b(3, 0.2), { o: 0 }]]);
  $$('.streams .base').forEach((el, k) => t([el], [[b(2, 0.05 + k * 0.05), { dash: 0 }], [b(2, 0.25 + k * 0.05), { dash: 1 }], [b(3, 0), { dash: 1 }], [b(3, 0.25), { dash: 0 }]]));
  $$('.streams .pulse').forEach((el, k) => t([el], [
    [b(2, 0.15), { o: 0, flow: k * 0.3 }], [b(2, 0.25), { o: 1 }], [b(3, 0), { o: 1 }], [b(3, 0.15), { o: 0, flow: 3 + k * 0.3 }, 'l'],
  ]));
  t('.pipe-line', [[b(2, 0.05), { o: 0 }], [b(2, 0.18), { o: 1 }], [b(3, 0.05), { o: 1 }], [b(3, 0.3), { o: 0 }]]);
  t('.pipe-line i', [[b(2, 0.3), { sx: 0 }], [b(2, 0.95), { sx: 1 }, 'l']]);
  $$('.step').forEach((el, k) => {
    const on = b(2, 0.3 + k * 0.108);
    t([el], [
      [b(2, 0.05 + k * 0.03), { o: 0, y: 20 }], [b(2, 0.18 + k * 0.03), { o: 1, y: 0, s: 1 }, 'b'],
      [on - 0.001, { on: 0 }], [on, { on: 1 }],
      [b(3, 0.05 + k * 0.02), { o: 1, s: 1 }], [b(3, 0.35 + k * 0.02), { o: 0, s: 0.6 }],
    ]);
  });
  t('.runner', [[b(2, 0.28), { x: 0, o: 0 }], [b(2, 0.3), { o: 1 }], [b(2, 0.95), { x: '38.2vw' }, 'l'], [b(3, 0.05), { o: 1 }], [b(3, 0.2), { o: 0 }]]);
  t('.clock', [[b(2, 0.25), { o: 0, y: 20 }], [b(2, 0.4), { o: 1, y: 0 }], [b(3, 0.05), { o: 1 }], [b(3, 0.25), { o: 0 }]]);
  t('.clock .hand', [[b(2, 0.3), { r: 0 }], [b(2, 0.95), { r: 1080 }, 'l']]);

  // ý 3 — dồn về một câu hỏi → bay sang cảnh 3
  t('.ask', [
    [b(3, 0.3), { o: 0 }], [b(3, 0.32), { o: 1 }],
    [b(3, 0.3), { cr: 0, s: 0.7 }], [b(3, 0.75), { cr: 150, s: 1 }, 'b'],
    [0.95, { x: 0, y: 0, s: 1 }], [1.06, { x: '-30.5vw', y: '-7vh', s: 0.55 }],
    [1.07, { o: 1 }], [1.1, { o: 0 }],
  ]);
  t('.concl', [[b(3, 0.35), { o: 0, y: 24 }], [b(3, 0.65), { o: 1, y: 0 }, 'o'], [0.95, { o: 1 }], [1.0, { o: 0 }]]);
  t('.tag', [[b(3, 0.6), { o: 0, y: 20 }], [b(3, 0.9), { o: 1, y: 0 }], [0.95, { o: 1 }], [1.0, { o: 0 }]]);
});
